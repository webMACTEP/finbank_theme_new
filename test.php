Поэтапный процесс оформления кредитки выглядит так:
<ul>
    <li>Заполнение анкеты и отправка её кредитору. Финансовые компании анализируют заявку, иногда связываются с клиентом по указанному телефонному номеру и после общения выносят решение. При маленьких лимитах многие банки перезвонов не делают.</li>
    <li>После того, как банк примет решение, заявителю озвучивают лимит и годовую процентную ставку.</li>
    <li>Если клиента всё устраивает, он подписывает договор (возможно, для подписания соглашения придётся посетить офис).</li>
    <li>После подписания договора банк занимается созданием кредитной карты, получить которую может пользователь в назначенное время.</li>
</ul>
<blockquote>На заметку. Если вам не нужны средства уже сейчас, то не стоит спешить с активацией карты. Пока кредитка не активирована, плата за её обслуживание не взимается.</blockquote>
